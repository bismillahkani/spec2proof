/* Optional browser QA + actual screen recording. npm install --no-save playwright */
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.SPEC2PROOF_PLAYWRIGHT || 'playwright');
(async () => {
  const output = path.resolve('docs/demo');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1060 }, recordVideo: { dir: output, size: { width: 1440, height: 1060 } } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const pause = () => page.waitForTimeout(1200);
  const base = process.env.SPEC2PROOF_DEMO_URL || 'http://127.0.0.1:8765';
  await page.goto(base);
  await pause();
  await page.screenshot({ path: path.join(output, '01-requirement.png'), fullPage: true });
  await page.getByRole('button', { name: 'Create acceptance criteria' }).click();
  await page.locator('#contract-card:not(.hidden)').waitFor();
  await pause();
  await page.locator('#confirm-contract').check();
  await page.getByRole('button', { name: 'Run Python tests', exact: true }).click();
  await page.getByRole('button', { name: 'Diagnose & propose repair' }).waitFor();
  await page.locator('#results').scrollIntoViewIfNeeded();
  await pause();
  await page.screenshot({ path: path.join(output, '02-failures.png'), fullPage: true });
  await page.getByRole('button', { name: 'Diagnose & propose repair' }).click();
  await page.locator('#patch-card:not(.hidden)').waitFor();
  await page.locator('#patch-card').scrollIntoViewIfNeeded();
  const reviewId = new URL(page.url()).searchParams.get('proof');
  await page.goto(base+'/?proof='+reviewId+'&view=approval#patch-card');
  await page.locator('#approval-controls:not(.hidden)').waitFor();
  if (new URL(page.url()).searchParams.get('state') !== 'awaiting_approval') throw new Error('Pending approval URL did not restore');
  await pause();
  if (!await page.locator('#approve').isDisabled()) throw new Error('Approval was not gated');
  await page.screenshot({ path: path.join(output, '03-review.png'), fullPage: true });
  await page.locator('#confirm-patch').check();
  await page.getByRole('button', { name: 'Approve patch & rerun tests' }).click();
  await page.getByText('Requirement verified against all 10 checks').waitFor();
  await page.locator('#results').scrollIntoViewIfNeeded();
  await pause();
  await page.screenshot({ path: path.join(output, '04-proof.png'), fullPage: true });
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download evidence .zip' }).click()]);
  await download.saveAs(path.join(output, 'sample-proof.zip'));
  const proofId = new URL(page.url()).searchParams.get('proof');
  if (new URL(page.url()).searchParams.get('state') !== 'verified') throw new Error('Verified URL state missing');
  await page.reload();
  await page.getByText('Requirement verified against all 10 checks').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, '05-mobile.png'), fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Mobile horizontal overflow');
  if (errors.length) throw new Error(errors.join('\n'));
  const video = page.video();
  await context.close();
  await video.saveAs(path.join(output, 'spec2proof-demo.webm'));
  await video.delete();
  await browser.close();
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ recorded_at: new Date().toISOString(), proof_id: proofId, checks: ['create', 'confirm contract', 'real baseline', 'propose', 'approval disabled before review', 'approve and rerun', 'download ZIP', 'reload persistence', '390px viewport without overflow'], browser_errors: errors, approval_actor: 'automated QA acting as reviewer; demo only' }, null, 2));
  console.log('Browser workflow passed; screenshots, evidence, and actual WebM recording saved to docs/demo.');
})().catch(error => { console.error(error); process.exit(1); });
